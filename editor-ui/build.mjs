// Editor-only build. Does not read game data, rewrite Trial bundles or deploy.
import { build } from 'vite';
import vue from '@vitejs/plugin-vue';
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { dirname, join, parse } from 'node:path';
const check = process.argv.includes('--check');
if (process.argv.slice(2).some(arg => arg !== '--check')) throw new Error('Unknown argument');
const root = fileURLToPath(new URL('.', import.meta.url));
const result = await build({
  configFile: false, root, plugins: [vue()],
  define: { 'process.env.NODE_ENV': JSON.stringify('production') },
  build: {
    write: false, minify: 'esbuild', target: 'es2022', sourcemap: false,
    lib: { entry: fileURLToPath(new URL('./src/main.js', import.meta.url)), formats: ['es'], fileName: () => 'shell-ui.js', cssFileName: 'shell-ui' },
    rollupOptions: { output: { inlineDynamicImports: true } },
  },
});
const outputs = Array.isArray(result) ? result.flatMap(item => item.output) : result.output;
for (const output of outputs) {
  if (!['shell-ui.js', 'shell-ui.css'].includes(output.fileName)) throw new Error('Unexpected build artifact: ' + output.fileName);
  const content = output.type === 'chunk' ? output.code : output.source;
  const target = new URL('../server/public/' + (output.fileName.endsWith('.js') ? 'shell-ui.txt' : output.fileName), import.meta.url);
  if (check) {
    if (!Buffer.from(content).equals(await readFile(target))) throw new Error('Stale editor UI: ' + output.fileName);
  } else await writeFile(target, content);
  process.stdout.write(`${check ? 'Verified' : 'Built'} ${output.fileName}: ${Buffer.byteLength(content)} bytes\n`);
}
if (outputs.length !== 2) throw new Error('Expected exactly one script and one stylesheet');

// Retain complete upstream notices for packages that contribute emitted JS.
// Element Plus also owns the emitted theme CSS. No CDN or runtime npm install.
const packages = new Map();
for (const chunk of outputs.filter(output => output.type === 'chunk')) {
  for (const [id, detail] of Object.entries(chunk.modules)) {
    if (!detail.renderedLength || !id.includes('/node_modules/')) continue;
    let directory = dirname(id.split('?')[0]);
    while (directory !== parse(directory).root) {
      let pkg;
      try { pkg = JSON.parse(await readFile(join(directory, 'package.json'), 'utf8')); } catch (error) { if (error.code !== 'ENOENT') throw error; }
      if (pkg?.name) {
        if (!packages.has(pkg.name)) {
          let license;
          for (const name of ['LICENSE', 'LICENSE.md', 'LICENSE.txt', 'license', 'license.md']) {
            try { license = await readFile(join(directory, name), 'utf8'); break; } catch (error) { if (error.code !== 'ENOENT') throw error; }
          }
          if (!license) throw new Error('Missing upstream notice: ' + pkg.name);
          packages.set(pkg.name, `${pkg.name}@${pkg.version} (${pkg.license})\n\n${license.trim()}`);
        }
        break;
      }
      directory = dirname(directory);
    }
  }
}
const notices = 'Editor UI third-party notices — generated by editor-ui/build.mjs\n\n' + [...packages.entries()].sort(([a], [b]) => { if (a < b) return -1; if (a > b) return 1; return 0; }).map(([, text]) => text).join('\n\n' + '='.repeat(72) + '\n\n') + '\n';
const target = new URL('../server/public/shell-ui-licenses.txt', import.meta.url);
if (check) {
  if (notices !== await readFile(target, 'utf8')) throw new Error('Stale editor UI notices');
} else await writeFile(target, notices);
process.stdout.write(`${check ? 'Verified' : 'Built'} notices for ${packages.size} packages\n`);
